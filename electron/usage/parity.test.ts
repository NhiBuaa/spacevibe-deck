import {
  cpSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  utimesSync,
  readdirSync,
  statSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
import { scanAll, buildSnapshot } from "./scan";
import { addCounters, emptyCache, type UsageBucket } from "./model";
import type { ResolveRepo } from "./repo-resolver";

/**
 * The parity gate: this scanner's totals must equal the snapshot the removed
 * Rust implementation produced over the same fixtures.
 *
 * `fixtures/golden-snapshot.json` was generated by the Rust scan over
 * `fixtures/home/` with every mtime pinned to T0 and the clock pinned to NOW.
 * The Rust side no longer exists, so the file is frozen: never regenerate it
 * from this scanner's own output, which would turn the gate into a
 * tautology. The golden predates the `repo` dimension, so the snapshot is
 * collapsed back to `(bucketStartMs, agent, model)` before comparing — which
 * is also the proof that splitting by repository changes no total. The
 * fixtures may gain fields Rust ignored (the Claude `cwd`), never usage.
 */

const T0 = 1_786_320_000_000; // 2026-08-10T00:00:00Z — every fixture's mtime
const NOW = 1_786_323_600_000; // T0 + 1h — the pinned scan clock

const FIXTURES = path.join(path.dirname(fileURLToPath(import.meta.url)), "fixtures");

// Every fixture cwd is redacted to one value; a stub answers for it so no
// test spawns git, and only with definitive answers so warm polls stay quiet.
const FIXTURE_CWD = "[redacted]";
const FIXTURE_REPO = "/repos/fixture";
const resolveFixtureRepo: ResolveRepo = async (cwd) =>
  cwd === FIXTURE_CWD ? { kind: "repo", root: FIXTURE_REPO } : { kind: "none" };

/** Sum over `repo`, keeping the pre-repo payload order. */
function collapseRepos(buckets: readonly UsageBucket[]): Omit<UsageBucket, "repo">[] {
  const merged = new Map<string, Omit<UsageBucket, "repo">>();
  for (const { repo: _repo, ...bucket } of buckets) {
    const key = JSON.stringify([bucket.bucketStartMs, bucket.agent, bucket.model]);
    const existing = merged.get(key);
    merged.set(
      key,
      existing === undefined
        ? bucket
        : { ...bucket, counters: addCounters(existing.counters, bucket.counters) },
    );
  }
  return [...merged.values()];
}

const temps: string[] = [];
afterEach(() => {
  for (const dir of temps.splice(0)) {
    rmSync(dir, { recursive: true, force: true });
  }
});

function pinTree(root: string): void {
  for (const entry of readdirSync(root)) {
    const target = path.join(root, entry);
    if (statSync(target).isDirectory()) {
      pinTree(target);
    }
    utimesSync(target, T0 / 1000, T0 / 1000);
  }
  utimesSync(root, T0 / 1000, T0 / 1000);
}

function fixtureHome(): string {
  const home = mkdtempSync(path.join(tmpdir(), "usage-parity-"));
  temps.push(home);
  // Git does not preserve mtimes, so the tree is re-pinned on every run —
  // the same pinning the golden generator applied.
  cpSync(path.join(FIXTURES, "home"), home, { recursive: true });
  pinTree(home);
  return home;
}

describe("Rust parity", () => {
  it("sums to exactly the snapshot the Rust scanner produced", async () => {
    const golden = JSON.parse(
      readFileSync(path.join(FIXTURES, "golden-snapshot.json"), "utf8"),
    ) as unknown;
    const home = fixtureHome();
    const outcome = await scanAll(emptyCache(), home, NOW, resolveFixtureRepo);
    const snapshot = buildSnapshot(outcome, NOW);
    expect({ ...snapshot, buckets: collapseRepos(snapshot.buckets) }).toEqual(golden);
    // Every fixture line names a cwd, and it resolved.
    expect(new Set(snapshot.buckets.map((bucket) => bucket.repo))).toEqual(new Set([FIXTURE_REPO]));
  });

  it("answers identically warm, without marking the cache changed", async () => {
    const home = fixtureHome();
    const cold = await scanAll(emptyCache(), home, NOW, resolveFixtureRepo);
    expect(cold.changed).toBe(true);
    const warm = await scanAll(cold.cache, home, NOW, resolveFixtureRepo);
    expect(warm.changed).toBe(false);
    expect(buildSnapshot(warm, NOW)).toEqual(buildSnapshot(cold, NOW));
  });
});
